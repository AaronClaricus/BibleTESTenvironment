const SearchController = {
    create({
        input,
        button,
        iframe,
        counter
    }) {
		if (
			!input ||
			!button ||
			!iframe ||
			!counter
		) {
			console.warn(
				"[SEARCH BIND SKIPPED]",
				{
					input,
					button,
					iframe,
					counter
				}
			);
			return;
		}
        const state = {
            matches: [],
            index: -1,
            lastTerm: ""
        };
        function updateCounter() {
            counter.textContent =
                state.matches.length === 0
                    ? "0/0"
                    : `${state.index + 1}/${state.matches.length}`;
        }
        function scrollToMatch(match) {
            const win =
                iframe.contentWindow;
            const rect =
                match.getBoundingClientRect();
            win.scrollTo({
                top:
                    win.scrollY +
                    rect.top -
                    CONFIG.search.scrollOffset,
                behavior: "auto"
            });
        }
        function resetSearch(term) {
            state.lastTerm =
                term;
            state.matches =
                SearchService.query(
                    iframe,
                    term
                );
            state.index =
                -1;
        }
        function advanceMatch() {
            if (!state.matches.length) {
                updateCounter();
                return;
            }
            state.index =
                (state.index + 1) %
                state.matches.length;
            scrollToMatch(
                state.matches[state.index]
            );
            updateCounter();
        }
        function runSearch() {
            const term =
                input.value.trim();
            if (!term) {
                return;
            }
            if (state.lastTerm !== term) {
                resetSearch(
                    term
                );
            }
            advanceMatch();
        }
        button.addEventListener(
            "click",
            runSearch
        );
        input.addEventListener(
            "keydown",
            e => {
                if (e.key === "Enter") {
                    runSearch();
                }
            }
        );
    }
};
