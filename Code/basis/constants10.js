const StateManager = {
    state: APP.state,
    listeners: {},
    get(path) {
        return path
            .split(".")
            .reduce(
                (obj,key)=>obj?.[key],
                this.state
            );
    },
    set(path,value) {

        const keys = path.split(".");
        const last = keys.pop();
        const target =
            keys.reduce(
                (obj,key)=>obj[key],
                this.state
            );
        target[last] = value;
        this.notify(path,value);
    },
	hydrate(){
    const settings =
        AppStorage.settings.load();
    if(settings){
        Object.assign(
            this.state.ui,
            settings
        );
    }
    this.state.app.lastOpened =
        AppStorage.lastOpened.load() || {};
},
    subscribe(path,callback) {
        if(!this.listeners[path]){

            this.listeners[path] = [];

        }
        this.listeners[path].push(callback);
    },
    notify(path,value){
        const listeners =
            this.listeners[path] || [];
        listeners.forEach(
            fn => fn(value)
        );
    }
};
